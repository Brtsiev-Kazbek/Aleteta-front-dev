/**
 * Промпты с номерами версий.
 *
 * Версия — не формальность: она входит в отпечаток задания. Поправили промпт,
 * не подняв версию, — исполнитель отдаст старый ответ из кэша, и вы решите,
 * что правка ничего не изменила. Поднимаете версию — прежние ответы перестают
 * подходить, и следующий запуск считает заново.
 *
 * ГДЕ ЛЕЖАТ САМИ ТЕКСТЫ. Задумывалось, что здесь, — их правят чаще всего, и
 * держать их рядом с остальным продуктовым кодом дешевле. На деле промпт
 * извлечения переехал в `supabase/functions/_shared/prompts.ts`: общего модуля
 * между приложением и Deno-функцией не выходит, а два «одинаковых» текста в
 * двух местах однажды уже разошлись — работал при этом тот, о котором никто не
 * помнил. Остальные тексты пока лежат тут и уедут туда же, когда под них
 * появятся обработчики.
 *
 * Что бы ни менялось, версия правится здесь: она входит в отпечаток задания.
 */

/** Версия промпта. Меняется при каждой правке текста. */
export const PROMPT_VERSIONS: Record<TypedTask, number> = {
  ocr: 1,
  /* 3: бюджет страниц в тексте промпта, примеры значений вернулись. */
  extract: 3,
  review: 1,
  assistant: 1,
  embed: 1,
};

/** Строка версии для отпечатка: `extract@1`. */
export function promptVersion(task: TypedTask): string {
  return `${task}@${PROMPT_VERSIONS[task]}`;
}

