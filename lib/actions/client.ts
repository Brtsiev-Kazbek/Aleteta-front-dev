import type { ActionResult } from "@/lib/actions/result";

/**
 * Вызов серверного действия, переживающий обрыв связи.
 *
 * ЗАЧЕМ. Серверное действие в Next — это запрос по сети, и он может не дойти:
 * сервер разработки перезапускается после правки, ноутбук проснулся со старым
 * соединением, вкладка провисела ночь. В этот момент промис отклоняется с
 * `TypeError: Failed to fetch`, и, если его никто не ловит, Next показывает
 * «Unhandled Runtime Error» поверх всей страницы.
 *
 * Экран при этом цел, данные целы, повторное нажатие сработало бы — но человек
 * видит красное полотно с трассировкой по внутренностям фреймворка и делает
 * единственно возможный вывод: сломалось всё.
 *
 * ПОЧЕМУ ОТДЕЛЬНАЯ ОБЁРТКА, А НЕ try/catch НА КАЖДОМ ВЫЗОВЕ. Мест вызова
 * четырнадцать, и это не предел: каждая новая форма — ещё одно. Обёртка
 * превращает обрыв в тот же самый `{ ok: false, error }`, который формы уже
 * умеют показывать, и новое место вызова получает защиту, ничего про неё не
 * зная.
 *
 * ОШИБКИ САМОГО ДЕЙСТВИЯ СЮДА НЕ ПОПАДАЮТ: ожидаемые отказы возвращаются
 * значением через `actionFail`, а исключение внутри действия ловит `actionError`
 * на сервере. Здесь остаётся ровно то, что случилось по дороге.
 */
export async function callAction<T>(
  request: Promise<ActionResult<T>>,
  fallback = "Не удалось связаться с сервером. Повторите."
): Promise<ActionResult<T>> {
  try {
    return await request;
  } catch (caught) {
    /*
     * Различаем обрыв и всё остальное. «Failed to fetch» — это сеть; любое
     * другое исключение здесь означает поломку в самом коде вызова, и прятать
     * её за вежливой фразой значит потерять её навсегда.
     */
    const isTransport =
      caught instanceof TypeError ||
      (caught instanceof Error && /fetch|network|load failed/i.test(caught.message));

    if (!isTransport && caught instanceof Error) {
      return { ok: false, error: caught.message };
    }

    return { ok: false, error: fallback };
  }
}
