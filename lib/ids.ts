/**
 * Отличает идентификатор, выданный базой, от временного.
 *
 * ЗАЧЕМ. Пока запись не сохранена — а во встроенном наборе она не сохраняется
 * никогда, — у неё номер из `nextId`: `doc-1786602393213-4`. Спросить сервер про
 * такой значит получить от Postgres «invalid input syntax for type uuid», причём
 * в цикле: состояние не меняется, наблюдатель не останавливается, и журнал
 * заполняется одной и той же жалобой.
 *
 * Именно так это и вылезло: страница распознавания открывалась на встроенном
 * наборе и на каждый показанный файл просила у хранилища ссылку по временному
 * номеру.
 *
 * ПРОВЕРКА ЖИВЁТ ОТДЕЛЬНО ОТ СЛОЁВ СТОРА, потому что нужна не только им: любой
 * компонент, зовущий серверное действие по идентификатору записи, обязан
 * спросить это первым.
 */

const UUID =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isPersistedId(id: string | null | undefined): boolean {
  return typeof id === "string" && UUID.test(id);
}
