import { IBM_Plex_Mono, Inter, Source_Serif_4 } from "next/font/google";

/**
 * Шрифты.
 *
 * До этого в проекте не было ни одного: интерфейс рисовался системным стеком и
 * выглядел по-разному в macOS, Windows и Linux. Для набора, целиком построенного
 * на моноширинных подписях в девять-одиннадцать пунктов с разрядкой, это не
 * мелочь: метрики Consolas и SF Mono расходятся настолько, что подпись, ровно
 * вставшая под колонку на одной машине, на другой уезжает.
 *
 * ОБЯЗАТЕЛЬНО КИРИЛЛИЦА. Без неё браузер подставит под русский текст первый
 * попавшийся системный шрифт, и получится ровно то, от чего уходим, — только
 * теперь вперемешку: латиница одним шрифтом, кириллица другим.
 *
 * Переменные подключаются к `--font-sans` и остальным в `globals.css`. Там же
 * лежат системные стеки: они остаются запасным вариантом, если шрифт не
 * доехал.
 */

/**
 * Inter — основной.
 *
 * Заодно начинает работать `font-feature-settings: "cv11", "ss01"`, которое
 * стояло в `globals.css` с самого начала и всё это время не делало ничего:
 * это настройки Inter, а Inter не был подключён. `cv11` даёт одноэтажную «a»,
 * `ss01` — открытую «g»; на мелких кеглях они читаются заметно лучше.
 */
export const sans = Inter({
  subsets: ["latin", "cyrillic"],
  display: "swap",
  variable: "--font-sans-loaded",
});

/**
 * IBM Plex Mono — подписи, номера, ключи.
 *
 * Выбран не за характер, а за кириллицу: у большинства моноширинных её либо нет,
 * либо она нарисована по остаточному принципу. Здесь моноширинным набрано
 * «РАСПОЗНАВАНИЕ» и «ДОКУМЕНТОВ: 12» — то есть русские слова, а не код.
 */
export const mono = IBM_Plex_Mono({
  subsets: ["latin", "cyrillic"],
  weight: ["400", "500"],
  display: "swap",
  variable: "--font-mono-loaded",
});

/**
 * Source Serif 4 — только крупные заголовки.
 *
 * Засечки здесь работают на смысл: продукт про документы, и заголовок,
 * набранный как в книге, задаёт верную интонацию. В мелких кеглях засечки
 * запрещены — там они мешают.
 */
export const serif = Source_Serif_4({
  subsets: ["latin", "cyrillic"],
  display: "swap",
  variable: "--font-serif-loaded",
});

/** Все переменные разом — вешаются на `<html>`. */
export const fontVariables = `${sans.variable} ${mono.variable} ${serif.variable}`;
