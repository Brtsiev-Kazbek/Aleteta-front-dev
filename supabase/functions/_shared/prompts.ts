/**
 * Тексты промптов исполнителя.
 *
 * ПОЧЕМУ ЗДЕСЬ, А НЕ В ПРИЛОЖЕНИИ. Хотелось бы держать промпты рядом с
 * остальным продуктовым кодом — их правят чаще всего. Но общего модуля между
 * приложением и Edge Function не получается: `supabase/functions` исключены из
 * `tsconfig.json`, а `lib/ai/prompts.ts` помечен `server-only` и тянет за собой
 * сборку Next.js, которой в Deno нет. Попытка «одного файла на двоих» кончилась
 * бы тем, чем уже однажды кончилась: текст лежал в двух местах, разошёлся, и
 * работал при этом тот, о котором никто не помнил.
 *
 * Поэтому правило простое: текст промпта живёт здесь и только здесь, а в
 * `lib/ai/prompts.ts` остаётся номер версии — он входит в отпечаток задания.
 *
 * ПРАВИТЕ ТЕКСТ — ПОДНИМИТЕ ВЕРСИЮ в `PROMPT_VERSIONS` (`lib/ai/prompts.ts`).
 * Иначе исполнитель отдаст на тот же вход старый ответ из журнала, и правку
 * невозможно будет проверить.
 */

/** Описание одного реквизита из `entity_types.fields`. */
export interface FieldSpec {
  key: string;
  label: string;
  required: boolean;
  /** Шаблон формата в виде регулярного выражения POSIX, если он задан у типа. */
  pattern?: string;
  placeholder?: string;
}

/**
 * Промпт извлечения строится из описания реквизитов конкретного типа объекта.
 *
 * Поэтому пользовательские типы работают без правки кода: человек завёл свой
 * тип «Транспортное средство» с полями «VIN» и «Госномер» — модель получает
 * ровно их и ищет в документе именно это.
 *
 * `pagesLooked`/`pagesTotal` попадают в текст не для красоты. Длинный документ
 * уходит в модель не целиком, и модель должна знать, что видит начало, а не
 * весь файл: иначе на вопрос «чего не хватает» она отвечает уверенным «этого в
 * документе нет», хотя нужное лежало на сороковой странице.
 */
export function buildExtractPrompt(
  typeLabel: string,
  fields: FieldSpec[],
  pages: { looked: number; total: number }
): string {
  const list = fields
    .map((field) => {
      const parts = [`- ${field.key} — ${field.label}`];
      if (field.required) parts.push("обязательное");
      if (field.pattern) parts.push(`формат: ${field.pattern}`);
      if (field.placeholder) parts.push(`пример: ${field.placeholder}`);
      return parts.join("; ");
    })
    .join("\n");

  const scope =
    pages.looked < pages.total
      ? `Тебе показаны первые ${pages.looked} ${plural(
          pages.looked,
          "страница",
          "страницы",
          "страниц"
        )} из ${pages.total}. Дальше документ не показан — если реквизита в этой части нет, так и пиши, не додумывая.`
      : `Документ показан целиком: ${pages.total} ${plural(
          pages.total,
          "страница",
          "страницы",
          "страниц"
        )}.`;

  return `Ты извлекаешь реквизиты из российского документа в карточку объекта «${typeLabel}».

${scope}

Нужно найти:
${list}

Правила:
1. Бери только то, что действительно написано в документе. Ничего не додумывай
   и не выводи по смыслу — пустое поле лучше выдуманного.
2. Значение переноси дословно, сохраняя формат оригинала: номера, даты и
   сокращения не «причёсывай».
3. Для каждого поля укажи уверенность от 0 до 1 и номер страницы, где нашёл.
4. Если поля в документе нет — не включай его в fields, впиши ключ в missing.

Ответ — JSON строго такого вида, без пояснений вокруг:
{"fields":[{"key":"...","value":"...","confidence":0.0,"page":1}],"missing":["..."]}`;
}

/** Русское склонение по числу. В приложении есть своё, но оно сюда не ходит. */
function plural(
  count: number,
  one: string,
  few: string,
  many: string
): string {
  const mod100 = count % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;

  const mod10 = count % 10;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}
