const workbench = await source("components/recognize/RecognizeWorkbench.tsx");

/*
 * Ручной расчёт прокрутки считает смещение относительно контейнера, который
 * прокручивается. Если контейнер перестанет быть прокручиваемым — потеряет
 * `overflow-y-auto` — или потеряет `min-h-0` и оттого перестанет ужиматься,
 * расчёт начнёт давать мусор, а поиск перестанет доводить до совпадения.
 * Именно так это уже ломалось: «не скроллится к найденному текст распознанный,
 * только пдф скроллится».
 */
report(
  workbench.includes("min-h-0") && workbench.includes("overflow-y-auto"),
  "у прокручиваемой панели текста остались min-h-0 и overflow-y-auto",
  "потеря любого из двух ломает ручной расчёт в scrollTo()"
);

/*
 * Якоря ищутся строкой через querySelector. Переименование шаблона не поймает
 * ни один компилятор: `#page-12` — это просто текст.
 */
report(
  workbench.includes("page-${") && workbench.includes("match-${"),
  "шаблоны якорей #page- и #match- на месте",
  "по ним ищет и переход по совпадениям, и синхронный скролл"
);

const highlight = await source("components/recognize/HighlightedText.tsx");
report(
  highlight.includes("`match-${number}`"),
  "подсветка по-прежнему раздаёт совпадениям сквозные номера",
  "без id=match-N стрелки «следующее совпадение» никуда не ведут"
);

/*
 * Порог, по которому определяется «текущая страница» при синхронном скролле,
 * выведен из нынешних отступов и высот заголовков. Меняя вертикальный ритм,
 * его надо пересчитать — страж не проверяет правильность числа, он лишь
 * напоминает, что число существует и живёт по соседству с версткой.
 */
const threshold = workbench.match(/distance\s*<=\s*(\d+)/);
report(
  threshold !== null,
  `порог выбора текущей страницы на месте (${threshold?.[1] ?? "?"}px)`,
  "если его убрали — синхронный скролл переключает страницу наугад"
);

