/*
 * Через границу «серверный компонент → клиентский» проходят только простые
 * значения. Объект класса — RegExp, Date, Map — Next отвергает целиком, и
 * страница отвечает пятисотой: «Only plain objects can be passed to Client
 * Components».
 *
 * Поймать это съёмкой нельзя: без базы снимок рабочей области пуст, и через
 * границу не идёт ничего. Именно так оно и проскочило — встроенные типы поехали
 * из базы вместе со своими шаблонами проверки, и приложение слегло на всех
 * внутренних экранах, а все проверки при этом были зелёными.
 */
const mappers = await source("lib/data/mappers.ts");
report(
  !/new RegExp|new Date|new Map|new Set/.test(mappers),
  "снимок рабочей области собран из простых значений",
  "объект класса не пройдёт из серверного компонента в клиентский — страница ляжет"
);

const typesFile = await source("types/index.ts");
report(
  /pattern\?: string;/.test(typesFile) && !/pattern\?: RegExp/.test(typesFile),
  "шаблон проверки хранится строкой, а не готовым выражением",
  "RegExp в описании типа доедет до клиента только через пятисотую ошибку"
);

const casePage = await source("app/cases/[id]/page.tsx");
report(
  casePage.includes('layoutId="case-tab-pill"') &&
    casePage.includes("data-underline"),
  "капсула вкладок дела на месте",
  "единственная анимация общего макета во всём проекте"
);

const split = await source("components/documents/ReviewSplitView.tsx");
report(
  split.includes("scroll-mt-"),
  "у абзацев разбора остался отступ прокрутки",
  "без него абзац при переходе упирается в верхнюю кромку панели"
);

const textarea = await source("components/ui/textarea.tsx");
report(
  textarea.includes("style.height"),
  "автовысота поля ввода на месте",
  "правка style.height — единственное, что растит его под текст"
);

/*
 * Замыкание не уезжает из серверного компонента в клиентский.
 *
 * Из-за чего страж. `<ActionButton action={() => someAction()} />` выглядит
 * безобидно и в клиентском компоненте таковым и является. В серверном это
 * пятисотая на первом же открытии: через границу проходят простые значения и
 * серверные действия, но не произвольные функции — «Functions cannot be passed
 * directly to Client Components».
 *
 * Ни сборка, ни типы этого не видят: ошибка возникает при отрисовке. Раздел
 * администрирования лёг ровно на этом, и заметить получилось только открыв
 * страницу под настоящей учётной записью — чего съёмка не делает.
 *
 * Правило простое: файл, передающий замыкание в `action`, обязан быть
 * клиентским.
 */
const actionUsers = [
  "components/admin/QueuePanel.tsx",
  "components/admin/JobsTable.tsx",
  "components/admin/UsersTable.tsx",
  "components/admin/WorkspacesTable.tsx",
];
const leaking = [];
for (const file of actionUsers) {
  const text = await source(file);
  if (/action=\{\s*\(\)\s*=>/.test(text) && !text.startsWith('"use client"')) {
    leaking.push(file);
  }
}
report(
  leaking.length === 0,
  "замыкания в action не уезжают за границу сервер → клиент",
  `без "use client" страница ляжет при отрисовке: ${leaking.join(", ")}`
);

/*
 * Раздел администрирования не ходит в базу служебным ключом.
 *
 * Из-за чего страж. Первая версия раздела читала данные клиентом со служебным
 * ключом, обходящим политики: одна ошибка в коде страницы означала бы выдачу
 * всех арендаторов разом. Теперь право проверяет сама база — в функциях
 * `platform_*`, — и служебный клиент здесь не нужен ни для чего.
 *
 * Соблазн вернуть его велик: с ним быстрее написать любой новый отчёт.
 */
const adminData = await source("lib/data/admin.ts");
report(
  !adminData.includes("createAdminClient") &&
    adminData.includes("platform_overview"),
  "админ-раздел читает через функции базы, а не служебным ключом",
  "createAdminClient обходит все политики: одна ошибка на странице — утечка всех пространств"
);

/*
 * Уважение к «уменьшить движение» не оставляет экран пустым.
 *
 * Из-за чего страж. Приём `initial={reduceMotion ? undefined : { opacity: 0 }}`
 * выглядит правильным и им не является. Первый клиентский рендер проходит,
 * когда хук ещё не ответил, — прозрачность выставляется в ноль; на втором
 * рендере пропсов уже нет, анимировать нечего, и элемент навсегда остаётся
 * невидимым. У человека с включённым «уменьшить движение» шапка рабочего стола
 * была пустым тёмным полем.
 *
 * Правильно — `initial={reduceMotion ? false : …}`: `false` означает «начать
 * сразу с конечных значений». Движения нет, содержимое на месте.
 */
const motionFiles = await Promise.all(
  [
    "components/dashboard/CabinetHeader.tsx",
    "components/dashboard/CabinetBento.tsx",
    "components/landing/Pricing.tsx",
  ].map(
    (file) => source(file)
  )
);
report(
  motionFiles.every(
    (file) =>
      !file.includes("initial={reduceMotion ? undefined") &&
      !/reduceMotion\s*\n?\s*\?\s*\{\}/.test(file)
  ),
  "«уменьшить движение» не прячет содержимое",
  "и `initial={reduceMotion ? undefined}`, и `reduceMotion ? {} : {…}` оставляют " +
    "прозрачность в нуле навсегда — нужен initial={false} при неизменном animate"
);

/*
 * Шкала кеглей известна `tailwind-merge`.
 *
 * Из-за чего страж. `cn("text-section", "text-fg")` без настройки возвращает
 * один `text-fg`: библиотека не знает имени `section`, относит его к цвету
 * текста и выбрасывает как конфликт. Заголовок молча теряет кегль — ни сборка,
 * ни линтер об этом не скажут. Так съехали все заголовки, собранные через `cn`,
 * и нашлось это на снимке, а не в коде.
 *
 * Страж сверяет два списка: ступени в конфиге Tailwind и ступени, перечисленные
 * в `lib/utils.ts`. Новая ступень, забытая во втором списке, — та же ошибка
 * заново.
 */
const tailwindConfig = await source("tailwind.config.ts");
const utils = await source("lib/utils.ts");

const fontSizeBlock = tailwindConfig.slice(
  tailwindConfig.indexOf("fontSize: {"),
  tailwindConfig.indexOf("fontFamily: {")
);
const steps = [...fontSizeBlock.matchAll(/^\s{8}"?([a-z-]+)"?:\s*\[/gm)].map(
  (match) => match[1]
);
const missing = steps.filter((step) => !utils.includes(`"${step}"`));

report(
  steps.length >= 10 && missing.length === 0,
  "шкала кеглей известна tailwind-merge",
  missing.length
    ? `нет в lib/utils.ts: ${missing.join(", ")} — эти классы будут молча съедены рядом с цветом`
    : "не нашлись ступени в tailwind.config.ts — проверьте разбор"
);

