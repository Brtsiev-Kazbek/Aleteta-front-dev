/**
 * Стражи хрупких мест.
 *
 * Проверки грубые — по исходному тексту, а не по поведению, — и это осознанный
 * размен. Места, за которыми они следят, поведением проверить отсюда нельзя:
 * ручной расчёт прокрутки в распознавании работает только на распознанном
 * документе, а такого в демонстрационном режиме нет. Выбор стоял между «никак»
 * и «грубо», и грубо оказалось лучше.
 *
 * Каждый страж родился из настоящей поломки. В комментарии к каждому написано,
 * из какой именно — иначе через месяц его снимут как непонятную придирку.
 *
 *   node scripts/guards.mjs
 */

import { readFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();

let total = 0;
let failed = 0;

async function source(file) {
  return readFile(path.join(ROOT, file), "utf8");
}

function report(ok, name, detail) {
  total += 1;

  if (ok) {
    console.log(`  ок   ${name}`);
    return;
  }
  failed += 1;
  console.log(`  СБОЙ ${name}`);
  console.log(`       ${detail}`);
}

/** Сколько раз подстрока встречается в тексте. */
function count(text, needle) {
  return text.split(needle).length - 1;
}

console.log("");

/* ------------------------------------------------------------------ */
/*  РАСПОЗНАВАНИЕ                                                      */
/* ------------------------------------------------------------------ */

const workbench = await source("components/recognize/RecognizeWorkbench.tsx");

/*
 * Ручной расчёт прокрутки считает смещение относительно контейнера, который
 * прокручивается. Если контейнер перестанет быть прокручиваемым — потеряет
 * `overflow-y-auto` — или потеряет `min-h-0` и оттого перестанет ужиматься,
 * расчёт начнёт давать мусор, а поиск перестанет доводить до совпадения.
 * Именно так это уже ломалось: «не скроллится к найденному текст распознанный,
 * только пдф скроллится».
 */
report(
  workbench.includes("min-h-0") && workbench.includes("overflow-y-auto"),
  "у прокручиваемой панели текста остались min-h-0 и overflow-y-auto",
  "потеря любого из двух ломает ручной расчёт в scrollTo()"
);

/*
 * Якоря ищутся строкой через querySelector. Переименование шаблона не поймает
 * ни один компилятор: `#page-12` — это просто текст.
 */
report(
  workbench.includes("page-${") && workbench.includes("match-${"),
  "шаблоны якорей #page- и #match- на месте",
  "по ним ищет и переход по совпадениям, и синхронный скролл"
);

const highlight = await source("components/recognize/HighlightedText.tsx");
report(
  highlight.includes("`match-${number}`"),
  "подсветка по-прежнему раздаёт совпадениям сквозные номера",
  "без id=match-N стрелки «следующее совпадение» никуда не ведут"
);

/*
 * Порог, по которому определяется «текущая страница» при синхронном скролле,
 * выведен из нынешних отступов и высот заголовков. Меняя вертикальный ритм,
 * его надо пересчитать — страж не проверяет правильность числа, он лишь
 * напоминает, что число существует и живёт по соседству с версткой.
 */
const threshold = workbench.match(/distance\s*<=\s*(\d+)/);
report(
  threshold !== null,
  `порог выбора текущей страницы на месте (${threshold?.[1] ?? "?"}px)`,
  "если его убрали — синхронный скролл переключает страницу наугад"
);

/* ------------------------------------------------------------------ */
/*  ТАБЛИЦА РЕКВИЗИТОВ                                                 */
/* ------------------------------------------------------------------ */

const grid = await source("components/workspace/BatchGenerationGrid.tsx");

/*
 * Приморозка держится на трёх вещах разом, и каждая по отдельности выглядит
 * необязательной: `border-separate` (при `border-collapse` границы примороженных
 * ячеек исчезают), тень вместо бордера (бордер у sticky уезжает) и `relative`
 * у контейнера (иначе ширина таблицы протекает в горизонтальный скролл всей
 * страницы).
 */
report(
  grid.includes("border-separate"),
  "таблица осталась на border-separate",
  "при border-collapse границы примороженных ячеек пропадают"
);

report(
  grid.includes("shadow-[1px_0_0_0_"),
  "граница примороженной колонки нарисована тенью",
  "обычный border у sticky-ячеек уезжает при прокрутке"
);

report(
  count(grid, "sticky z-10") >= 2,
  "приморозка стоит и на заголовке, и на ячейке",
  "одна без другой даёт разъезжающуюся шапку"
);

/*
 * Высота строки продублирована в шести местах — по одному на каждое из пяти
 * состояний ячейки плюс статус. Расхождение хотя бы в одном даёт рваную сетку,
 * которую замечают не сразу и списывают на «так и было».
 */
/*
 * Семь: ячейка состояния, ячейка действий и пять взаимоисключающих видов самой
 * ячейки реквизита — правка, ошибка, пусто, «модель не уверена», обычный.
 * Число проверяется, а не выводится, потому что ошибиться в нём легко: янтарная
 * ветка появилась позже остальных, и её высоту забыли бы не задать.
 */
const ROW_BRANCHES = 7;
const rowHeight = count(grid, "h-11") + count(grid, "h-[var(--row-h)]");
report(
  rowHeight === ROW_BRANCHES,
  `высота строки задана во всех ${ROW_BRANCHES} ветках одинаково`,
  `нашлось ${rowHeight} вместо ${ROW_BRANCHES} — либо ветку добавили без высоты, ` +
    "либо одну расходили с остальными, и сетка станет рваной"
);

/*
 * Порядок состояний ячейки значим: ошибка главнее «неуверенно», иначе поле с
 * неверным форматом покажется янтарным вместо красного и человек решит, что
 * его достаточно проверить, а не исправить.
 */
const errorAt = grid.indexOf("if (error)");
const uncertainAt = grid.indexOf("uncertainFields.includes");
report(
  errorAt > 0 && uncertainAt > 0 && errorAt < uncertainAt,
  "ошибка проверяется раньше «модель не уверена»",
  "иначе неверный формат покажется янтарным вместо красного"
);

/* ------------------------------------------------------------------ */
/*  ПРОЧЕЕ                                                             */
/* ------------------------------------------------------------------ */

/*
 * Через границу «серверный компонент → клиентский» проходят только простые
 * значения. Объект класса — RegExp, Date, Map — Next отвергает целиком, и
 * страница отвечает пятисотой: «Only plain objects can be passed to Client
 * Components».
 *
 * Поймать это съёмкой нельзя: без базы снимок рабочей области пуст, и через
 * границу не идёт ничего. Именно так оно и проскочило — встроенные типы поехали
 * из базы вместе со своими шаблонами проверки, и приложение слегло на всех
 * внутренних экранах, а все проверки при этом были зелёными.
 */
const mappers = await source("lib/data/mappers.ts");
report(
  !/new RegExp|new Date|new Map|new Set/.test(mappers),
  "снимок рабочей области собран из простых значений",
  "объект класса не пройдёт из серверного компонента в клиентский — страница ляжет"
);

const typesFile = await source("types/index.ts");
report(
  /pattern\?: string;/.test(typesFile) && !/pattern\?: RegExp/.test(typesFile),
  "шаблон проверки хранится строкой, а не готовым выражением",
  "RegExp в описании типа доедет до клиента только через пятисотую ошибку"
);

const casePage = await source("app/cases/[id]/page.tsx");
report(
  casePage.includes('layoutId="case-tab-underline"'),
  "подчёркивание вкладок дела на месте",
  "единственная анимация общего макета во всём проекте"
);

const split = await source("components/documents/ReviewSplitView.tsx");
report(
  split.includes("scroll-mt-"),
  "у абзацев разбора остался отступ прокрутки",
  "без него абзац при переходе упирается в верхнюю кромку панели"
);

const textarea = await source("components/ui/textarea.tsx");
report(
  textarea.includes("style.height"),
  "автовысота поля ввода на месте",
  "правка style.height — единственное, что растит его под текст"
);

/* ------------------------------------------------------------------ */

console.log(
  `\n${total - failed} из ${total} стражей довольны${failed ? "" : " — хрупкие места целы"}\n`
);

process.exit(failed > 0 ? 1 : 0);
