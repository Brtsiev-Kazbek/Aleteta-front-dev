const grid = await source("components/workspace/BatchGenerationGrid.tsx");

/*
 * Приморозка держится на трёх вещах разом, и каждая по отдельности выглядит
 * необязательной: `border-separate` (при `border-collapse` границы примороженных
 * ячеек исчезают), тень вместо бордера (бордер у sticky уезжает) и `relative`
 * у контейнера (иначе ширина таблицы протекает в горизонтальный скролл всей
 * страницы).
 */
report(
  grid.includes("border-separate"),
  "таблица осталась на border-separate",
  "при border-collapse границы примороженных ячеек пропадают"
);

report(
  grid.includes("shadow-[1px_0_0_0_"),
  "граница примороженной колонки нарисована тенью",
  "обычный border у sticky-ячеек уезжает при прокрутке"
);

report(
  count(grid, "sticky z-10") >= 2,
  "приморозка стоит и на заголовке, и на ячейке",
  "одна без другой даёт разъезжающуюся шапку"
);

/*
 * Высота строки продублирована в шести местах — по одному на каждое из пяти
 * состояний ячейки плюс статус. Расхождение хотя бы в одном даёт рваную сетку,
 * которую замечают не сразу и списывают на «так и было».
 */
/*
 * Семь: ячейка состояния, ячейка действий и пять взаимоисключающих видов самой
 * ячейки реквизита — правка, ошибка, пусто, «модель не уверена», обычный.
 * Число проверяется, а не выводится, потому что ошибиться в нём легко: янтарная
 * ветка появилась позже остальных, и её высоту забыли бы не задать.
 */
const ROW_BRANCHES = 7;
const rowHeight =
  count(grid, "h-row") + count(grid, "h-11") + count(grid, "h-[var(--row-h)]");
report(
  rowHeight === ROW_BRANCHES,
  `высота строки задана во всех ${ROW_BRANCHES} ветках одинаково`,
  `нашлось ${rowHeight} вместо ${ROW_BRANCHES} — либо ветку добавили без высоты, ` +
    "либо одну расходили с остальными, и сетка станет рваной"
);

/*
 * Порядок состояний ячейки значим: ошибка главнее «неуверенно», иначе поле с
 * неверным форматом покажется янтарным вместо красного и человек решит, что
 * его достаточно проверить, а не исправить.
 */
const errorAt = grid.indexOf("if (error)");
const uncertainAt = grid.indexOf("uncertainFields.includes");
report(
  errorAt > 0 && uncertainAt > 0 && errorAt < uncertainAt,
  "ошибка проверяется раньше «модель не уверена»",
  "иначе неверный формат покажется янтарным вместо красного"
);

