/**
 * Стражи хрупких мест.
 *
 * Проверки грубые — по исходному тексту, а не по поведению, — и это осознанный
 * размен. Места, за которыми они следят, поведением проверить отсюда нельзя:
 * ручной расчёт прокрутки в распознавании работает только на распознанном
 * документе, а такого в демонстрационном режиме нет. Выбор стоял между «никак»
 * и «грубо», и грубо оказалось лучше.
 *
 * Каждый страж родился из настоящей поломки. В комментарии к каждому написано,
 * из какой именно — иначе через месяц его снимут как непонятную придирку.
 *
 *   node scripts/guards.mjs
 */

import { readFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();

let total = 0;
let failed = 0;

async function source(file) {
  return readFile(path.join(ROOT, file), "utf8");
}

function report(ok, name, detail) {
  total += 1;

  if (ok) {
    console.log(`  ок   ${name}`);
    return;
  }
  failed += 1;
  console.log(`  СБОЙ ${name}`);
  console.log(`       ${detail}`);
}

/** Сколько раз подстрока встречается в тексте. */
function count(text, needle) {
  return text.split(needle).length - 1;
}

console.log("");

